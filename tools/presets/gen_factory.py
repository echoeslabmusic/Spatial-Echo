#!/usr/bin/env python3
"""Generate FactoryPresetLibrary.h from the factory preset roster.

Run with the system Python; no analysis environment is required:

    python3 tools/presets/gen_factory.py

The generator validates the complete schema and load-time contract before it
touches the header. ``--check`` validates and reports whether the committed
header is current without writing it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from validate_values import (
    MIX_FLOORS,
    PARAMETER_COUNT,
    REFERENCE_SCHEMA,
    ROSTER_SCHEMA,
    validate_table,
)
from check_story import check_story

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
ROSTER = HERE / "roster-values.json"
REFERENCE = HERE / "param-reference.json"
HEADER = ROOT / "plugin/Source/Presets/FactoryPresetLibrary.h"

# Browser order and user-facing labels. The floor values must stay identical to
# the validator's load-time contract.
CATEGORIES = [
    ("spatial_anchors", "Spatial Anchors", 0.52),
    ("mix_utilities", "Mix Utilities", 0.45),
    ("throws", "Throws", 0.52),
    ("orbits", "Orbits", 0.54),
    ("cloud_beds", "Reverb Beds", 0.54),
    ("dub_feedback", "Dub Feedback", 0.50),
    ("glitch_patterns", "Glitch Patterns", 0.50),
    ("transitions_impacts", "Transitions & Impacts", 0.54),
    ("psycho_lab", "Perception Lab", 0.52),
    ("motion_lab", "Motion Lab", 0.52),
]


def _float_literal(value: float) -> str:
    numeric = float(value)
    if numeric == 0.0:
        numeric = 0.0
    if numeric.is_integer():
        return f"{int(numeric)}.0f"
    return f"{format(numeric, '.9g')}f"


def _cpp_string(value: str) -> str:
    """JSON's quoted ASCII form is also a valid C++ string literal here."""
    return json.dumps(value, ensure_ascii=True)


def _load_and_validate() -> tuple[dict[str, Any], dict[str, Any]]:
    try:
        reference = json.loads(REFERENCE.read_text(encoding="utf-8"))
        roster = json.loads(ROSTER.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"cannot read generator inputs: {exc}") from exc

    issues = validate_table(roster, reference)
    if issues:
        detail = "\n".join(f" - {issue}" for issue in issues)
        raise SystemExit(
            "roster validation failed; refusing to generate FactoryPresetLibrary.h:\n"
            + detail
        )

    story_issues = check_story(roster, reference)
    if story_issues:
        detail = "\n".join(f" - {issue}" for issue in story_issues)
        raise SystemExit(
            "preset story validation failed; refusing to generate "
            "FactoryPresetLibrary.h:\n" + detail
        )

    # Keep the generator's compatibility boundary explicit even though the
    # shared validator already checks it.
    if reference["schema"] != REFERENCE_SCHEMA:
        raise SystemExit(f"expected parameter reference {REFERENCE_SCHEMA}")
    if roster["schema"] != ROSTER_SCHEMA:
        raise SystemExit(f"expected roster {ROSTER_SCHEMA}")
    if roster["parameter_order"] != reference["order"]:
        raise SystemExit("roster parameter_order differs from param-reference.json")
    if len(reference["order"]) != PARAMETER_COUNT:
        raise SystemExit(
            f"parameter_order has {len(reference['order'])} entries, expected {PARAMETER_COUNT}"
        )

    generator_floors = {category: floor for category, _, floor in CATEGORIES}
    if generator_floors != MIX_FLOORS:
        raise SystemExit("generator category table differs from validator category floors")

    return roster, reference


def _render_header(roster: dict[str, Any], reference: dict[str, Any]) -> str:
    params: list[str] = roster["parameter_order"]
    presets: list[dict[str, Any]] = roster["presets"]
    preset_count = len(presets)
    pattern_names: list[str] = reference["params"]["SpatialPattern"]["choices"]
    pattern_index = params.index("SpatialPattern")
    depth_index = params.index("SpatialDepth")

    output: list[str] = []
    output.append(
        f"// FactoryPresetLibrary: static factory preset definitions and metadata for all {preset_count} Spatial Echo presets."
    )
    output.append("// Generated by tools/presets/gen_factory.py from roster-values.json; do not hand-edit preset values.")
    output.append("// See docs/preset-system.md.")
    output.append("// clang-format off")
    output.append("")
    output.append("#pragma once")
    output.append("")
    output.append("#include <array>")
    output.append("#include <cstddef>")
    output.append("#include <cstring>")
    output.append("")
    output.append("namespace FactoryPresetLibrary")
    output.append("{")
    output.append(
        f"inline constexpr size_t kFactoryPresetParameterCount = {PARAMETER_COUNT};"
    )
    output.append("")
    output.append("struct FactoryPresetDefinition")
    output.append("{")
    output.append("    const char* name;")
    output.append("    const char* category;")
    output.append("    std::array<float, kFactoryPresetParameterCount> values;")
    output.append("};")
    output.append("")
    output.append("struct FactoryPresetCategoryDefinition")
    output.append("{")
    output.append("    const char* id;")
    output.append("    const char* label;")
    output.append("    float mixFloor;")
    output.append("};")
    output.append("")
    output.append(
        "inline constexpr std::array<FactoryPresetCategoryDefinition, "
        f"{len(CATEGORIES)}> kFactoryPresetCategories = {{{{"
    )
    for category_id, label, floor in CATEGORIES:
        output.append(
            f"    {{ {_cpp_string(category_id)}, {_cpp_string(label)}, {floor:.2f}f }},"
        )
    output.append("}};")
    output.append("")
    output.append(
        "inline const FactoryPresetCategoryDefinition* "
        "findFactoryPresetCategory(const char* categoryId)"
    )
    output.append("{")
    output.append("    if (categoryId == nullptr)")
    output.append("        return nullptr;")
    output.append("")
    output.append("    for (const auto& category : kFactoryPresetCategories)")
    output.append("        if (std::strcmp(category.id, categoryId) == 0)")
    output.append("            return &category;")
    output.append("")
    output.append("    return nullptr;")
    output.append("}")
    output.append("")
    output.append("inline bool factoryPresetCategoryExists(const char* categoryId)")
    output.append("{")
    output.append("    return findFactoryPresetCategory(categoryId) != nullptr;")
    output.append("}")
    output.append("")
    output.append("inline float getFactoryPresetCategoryMixFloor(const char* categoryId)")
    output.append("{")
    output.append("    if (const auto* category = findFactoryPresetCategory(categoryId))")
    output.append("        return category->mixFloor;")
    output.append("")
    output.append("    return 0.48f;")
    output.append("}")
    output.append("")
    output.append("// Parameter order is fixed and shared by all presets.")
    output.append(
        "inline constexpr std::array<const char*, kFactoryPresetParameterCount> "
        "kParameterIds = {"
    )
    for parameter_id in params:
        output.append(f"    {_cpp_string(parameter_id)},")
    output.append("};")
    output.append("")
    output.append(
        "inline constexpr std::array<FactoryPresetDefinition, "
        f"{preset_count}> kFactoryPresets = {{"
    )
    for preset in presets:
        values = [preset["values"][parameter_id] for parameter_id in params]
        pattern = int(values[pattern_index])
        depth = values[depth_index]
        pattern_name = pattern_names[pattern]
        output.append("    FactoryPresetDefinition{")
        output.append(f"        {_cpp_string(preset['name'])},")
        output.append(
            f"        {_cpp_string(preset['category'])},  // Pattern: {pattern} "
            f"({pattern_name}), Depth: {format(float(depth), '.6g')}"
        )
        output.append("        {")
        tokens = [_float_literal(value) for value in values]
        for row in range(0, len(tokens), 8):
            suffix = "," if row + 8 < len(tokens) else ""
            output.append("            " + ", ".join(tokens[row : row + 8]) + suffix)
        output.append("        }")
        output.append("    },")
    output.append("};")
    output.append("")
    output.append("inline constexpr size_t kNumFactoryPresets = kFactoryPresets.size();")
    output.append(
        "inline constexpr size_t kNumFactoryPresetParameters = kParameterIds.size();"
    )
    output.append("")
    output.append("} // namespace FactoryPresetLibrary")
    output.append("")
    return "\n".join(output)


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="validate inputs and require the generated header to be current without writing",
    )
    return parser.parse_args()


def main() -> int:
    args = _parse_args()
    roster, reference = _load_and_validate()
    rendered = _render_header(roster, reference)

    if args.check:
        try:
            current = HEADER.read_text(encoding="utf-8")
        except OSError as exc:
            print(f"cannot read {HEADER}: {exc}")
            return 1
        if current != rendered:
            print(f"stale generated header: {HEADER}")
            return 1
        print(
            f"current: {HEADER} ({len(roster['presets'])} presets, {len(CATEGORIES)} categories, "
            f"{PARAMETER_COUNT} parameters)"
        )
        return 0

    HEADER.write_text(rendered, encoding="utf-8")
    print(
        f"wrote {HEADER} ({len(roster['presets'])} presets, {len(CATEGORIES)} categories, "
        f"{PARAMETER_COUNT} parameters)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
